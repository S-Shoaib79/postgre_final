-- ============================================================================
-- Secure-ERMS PoC — PostgreSQL schema
-- Version: 1.0 | 2026-11-10
-- Baseline: agreed domain model and complete database schema diagram.
--
-- Three groups:
--   1. Application-wide metadata (roles, protected types, RBAC eligibility)
--   2. Tenant-specific business data
--   3. Tenant-specific security data (protected-type ownership)
--
-- Deliberately NOT included: compensation/bank history, role ownership,
-- authorization request workflow, RLS policies, encryption/AM internals,
-- session management and credential provisioning implementation.
-- PostgreSQL column types below are logical/plaintext SQL types; actual
-- cryptographic enforcement belongs to the patched PostgreSQL + Discreet AM.
-- No DROP TABLE statements: intended for a fresh database/schema.
-- ============================================================================

BEGIN;

-- 1. APPLICATION-WIDE METADATA -----------------------------------------------

CREATE TABLE roles (
    role_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name     VARCHAR(30) NOT NULL UNIQUE,
    description   VARCHAR(255),
    CONSTRAINT ck_roles_predefined CHECK (role_name IN (
        'TENANT_ADMIN', 'HR_ADMIN', 'HR_MANAGER',
        'DEPT_MANAGER', 'PAYROLL_OFFICER', 'EMPLOYEE'
    ))
);

CREATE TABLE protected_type_catalog (
    type_id       VARCHAR(10) PRIMARY KEY,
    type_name     VARCHAR(50) NOT NULL,
    table_name    VARCHAR(63) NOT NULL,
    column_name   VARCHAR(63) NOT NULL,
    java_class    VARCHAR(255) NOT NULL,
    description   VARCHAR(255),
    CONSTRAINT uq_protected_column UNIQUE (table_name, column_name)
);

CREATE TABLE role_protected_type_permissions (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       BIGINT NOT NULL REFERENCES roles (role_id),
    type_id       VARCHAR(10) NOT NULL REFERENCES protected_type_catalog (type_id),
    can_select    BOOLEAN NOT NULL DEFAULT FALSE,
    can_insert    BOOLEAN NOT NULL DEFAULT FALSE,
    can_update    BOOLEAN NOT NULL DEFAULT FALSE,
    can_delete    BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_role_protected_type UNIQUE (role_id, type_id)
);

-- 2. TENANT-SPECIFIC BUSINESS DATA --------------------------------------------

CREATE TABLE tenants (
    tenant_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_code        VARCHAR(40) NOT NULL UNIQUE,
    org_name        VARCHAR(160) NOT NULL,
    contact_phone   VARCHAR(30),
    registered_on   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT ck_tenant_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT NOT NULL REFERENCES tenants (tenant_id),
    name          VARCHAR(100) NOT NULL,
    CONSTRAINT uq_department_name_per_tenant UNIQUE (tenant_id, name),
    CONSTRAINT uq_department_tenant_pair UNIQUE (tenant_id, department_id)
);

CREATE TABLE employees (
    employee_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT NOT NULL REFERENCES tenants (tenant_id),
    department_id  BIGINT,
    role_id        BIGINT NOT NULL REFERENCES roles (role_id),
    first_name     VARCHAR(50) NOT NULL,
    last_name      VARCHAR(50) NOT NULL,
    date_of_birth  DATE,
    ssn            VARCHAR(50),
    hire_date      DATE,
    status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT ck_employee_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'TERMINATED')),
    CONSTRAINT uq_employee_tenant_pair UNIQUE (tenant_id, employee_id),
    CONSTRAINT fk_employee_same_tenant_department
        FOREIGN KEY (tenant_id, department_id)
        REFERENCES departments (tenant_id, department_id)
);

-- The employee department is nullable for the initial TENANT_ADMIN bootstrap.
-- Non-admin employee department assignment is enforced by provisioning rules;
-- a CHECK cannot compare a role_id to a row in the roles table.

CREATE TABLE user_accounts (
    user_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT NOT NULL REFERENCES tenants (tenant_id),
    employee_id           BIGINT NOT NULL,
    username              VARCHAR(80) NOT NULL,
    password_hash         VARCHAR(255) NOT NULL,
    status                VARCHAR(24) NOT NULL DEFAULT 'PENDING_FIRST_LOGIN',
    must_change_password  BOOLEAN NOT NULL DEFAULT TRUE,
    created_on            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activated_on          TIMESTAMPTZ,
    CONSTRAINT ck_user_account_status
        CHECK (status IN ('PENDING_FIRST_LOGIN', 'ACTIVE', 'DISABLED')),
    CONSTRAINT uq_username_per_tenant UNIQUE (tenant_id, username),
    CONSTRAINT uq_account_per_employee UNIQUE (tenant_id, employee_id),
    CONSTRAINT fk_account_same_tenant_employee
        FOREIGN KEY (tenant_id, employee_id)
        REFERENCES employees (tenant_id, employee_id)
);

-- UNIQUE + NOT NULL above enforces at most one account per employee and
-- exactly one employee per account. The reciprocal "every employee has an
-- account" invariant requires controlled same-transaction provisioning or
-- additional deferred database logic; this is not implied by a single FK.

CREATE TABLE compensation (
    compensation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT NOT NULL REFERENCES tenants (tenant_id),
    employee_id     BIGINT NOT NULL,
    base_salary     NUMERIC(15,2) NOT NULL,
    CONSTRAINT ck_compensation_nonnegative CHECK (base_salary >= 0),
    CONSTRAINT uq_compensation_per_employee UNIQUE (tenant_id, employee_id),
    CONSTRAINT fk_compensation_same_tenant_employee
        FOREIGN KEY (tenant_id, employee_id)
        REFERENCES employees (tenant_id, employee_id)
);

CREATE TABLE bank_accounts (
    bank_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT NOT NULL REFERENCES tenants (tenant_id),
    employee_id     BIGINT NOT NULL,
    account_number  VARCHAR(50) NOT NULL,
    bank_name       VARCHAR(100) NOT NULL,
    CONSTRAINT uq_bank_account_per_employee UNIQUE (tenant_id, employee_id),
    CONSTRAINT fk_bank_account_same_tenant_employee
        FOREIGN KEY (tenant_id, employee_id)
        REFERENCES employees (tenant_id, employee_id)
);

-- 3. TENANT-SPECIFIC SECURITY DATA --------------------------------------------

CREATE TABLE asset_owner_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT NOT NULL REFERENCES tenants (tenant_id),
    employee_id   BIGINT NOT NULL,
    type_id       VARCHAR(10) NOT NULL REFERENCES protected_type_catalog (type_id),
    assigned_on   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_on    TIMESTAMPTZ,
    revoked_by    BIGINT,
    CONSTRAINT ck_assignment_revocation_time
        CHECK (revoked_on IS NULL OR revoked_on >= assigned_on),
    CONSTRAINT ck_assignment_revocation_fields
        CHECK (revoked_by IS NULL OR revoked_on IS NOT NULL),
    CONSTRAINT fk_owner_same_tenant_employee
        FOREIGN KEY (tenant_id, employee_id)
        REFERENCES employees (tenant_id, employee_id),
    CONSTRAINT fk_revoker_same_tenant_employee
        FOREIGN KEY (tenant_id, revoked_by)
        REFERENCES employees (tenant_id, employee_id)
);

-- Multiple owners can exist for the same (tenant, protected type), but a
-- specific employee can have only one active assignment of that type.
CREATE UNIQUE INDEX uq_active_asset_owner_assignment
    ON asset_owner_assignments (tenant_id, employee_id, type_id)
    WHERE revoked_on IS NULL;

-- Additional non-unique indexes on FK paths useful for tenant-scoped joins.
CREATE INDEX ix_employees_tenant_role
    ON employees (tenant_id, role_id);
CREATE INDEX ix_accounts_tenant_status
    ON user_accounts (tenant_id, status);
CREATE INDEX ix_owner_assignments_active_type
    ON asset_owner_assignments (tenant_id, type_id)
    WHERE revoked_on IS NULL;
CREATE INDEX ix_role_type_permissions_type
    ON role_protected_type_permissions (type_id);

-- Immutable business role assignments: this PoC does not permit role changes.
-- Any future design that allows role reassignment must explicitly replace this
-- trigger and coordinate related RBAC/AM revocation and reauthorization.
CREATE FUNCTION reject_employee_role_change() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.role_id IS DISTINCT FROM OLD.role_id THEN
        RAISE EXCEPTION 'Employee business role is immutable in this PoC';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_employee_role_immutable
    BEFORE UPDATE OF role_id ON employees
    FOR EACH ROW EXECUTE FUNCTION reject_employee_role_change();

